import org.gradle.api.DefaultTask
import org.gradle.api.file.ConfigurableFileCollection
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputFiles
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction
import java.io.File
import java.util.Properties

/**
 * Bundles the store changelog of the version being built into the app, so "What's new" reads the same text the
 * stores show and the app needs no network.
 *
 * The notes are `fastlane/metadata/android/<locale>/changelogs/<versionCode>.txt`; [changelogs] is those files of
 * the one version, and the locale is the name of the folder two levels above each. They become one Kotlin object
 * (see [changelogSource]). A locale without the file is left out, and a version with none at all (the notes are
 * written when the release is cut) gives an empty map: the app then has no notes to show.
 */
@CacheableTask
abstract class GenerateChangelogs : DefaultTask() {
    /** The version's `<versionCode>.txt` of every locale. */
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val changelogs: ConfigurableFileCollection

    @get:Input
    abstract val versionCode: Property<Int>

    /** The source root the generated Kotlin file is written under. */
    @get:OutputDirectory
    abstract val output: DirectoryProperty

    @TaskAction
    fun generate() {
        val notes = changelogs.files
            .filter { it.isFile && it.name == "${versionCode.get()}.txt" }
            .associate { it.parentFile.parentFile.name to it.readText() }
        val target = output.get().asFile.resolve(CHANGELOGS_FILE)
        target.parentFile.mkdirs()
        target.writeText(changelogSource(versionCode.get(), notes))
    }

    private companion object {
        const val CHANGELOGS_FILE = "com/pasich/encly/whatsnew/BundledChangelogs.kt"
    }
}

/** The Kotlin source of `BundledChangelogs`: [notes] (locale folder to text) of the version [versionCode]. */
fun changelogSource(versionCode: Int, notes: Map<String, String>): String = buildString {
    appendLine("package com.pasich.encly.whatsnew")
    appendLine()
    appendLine("// Generated by the GenerateChangelogs task from fastlane/metadata/android; do not edit.")
    appendLine("internal object BundledChangelogs {")
    appendLine("    const val VERSION_CODE: Int = $versionCode")
    appendLine()
    appendLine("    /** The store changelog of [VERSION_CODE] by locale folder (`en-US`, `uk`, ...). */")
    appendLine("    val notes: Map<String, String> = mapOf(")
    notes.toSortedMap().forEach { (locale, text) ->
        appendLine("        ${literal(locale)} to ${literal(text.trim())},")
    }
    appendLine("    )")
    appendLine("}")
}

/** [text] as a Kotlin string literal: quotes, backslashes, `$` and line breaks escaped. */
private fun literal(text: String): String = buildString {
    append('"')
    text.forEach { char ->
        when (char) {
            '\\' -> append("\\\\")
            '"' -> append("\\\"")
            '$' -> append("\\$")
            '\n' -> append("\\n")
            '\r' -> Unit
            '\t' -> append("\\t")
            else -> append(char)
        }
    }
    append('"')
}

/** The version code of `version.properties`, derived like the app's: `MAJOR * 10000 + MINOR * 100 + PATCH`. */
fun versionCodeOf(versionProperties: File): Int {
    val properties = Properties().apply { versionProperties.inputStream().use { load(it) } }
    fun part(name: String) = properties.getProperty(name).trim().toInt()
    return part("VERSION_MAJOR") * 10000 + part("VERSION_MINOR") * 100 + part("VERSION_PATCH")
}
